void RetroFont::draw_glyph(SDL_Renderer* renderer, char c, int x, int y, Color color, int scale) {
    if (c < 32 || c > 126) c = '?';
    int index = c - 32;

    SDL_SetRenderDrawColor(renderer, color.r, color.g, color.b, color.a);
    for (int row = 0; row < 8; ++row) {
        uint8_t byte = FONT_8X8[index][row];
        for (int col = 0; col < 8; ++col) {
            if (byte & (0x80 >> col)) {
                if (scale == 1) {
                    SDL_RenderDrawPoint(renderer, x + col, y + row);
                } else {
                    SDL_Rect rect = { x + col * scale, y + row * scale, scale, scale };
                    SDL_RenderFillRect(renderer, &rect);
                }
            }
        }
    }
}

void RetroFont::draw_text(SDL_Renderer* renderer, const std::string& text, int x, int y, Color color, int scale) {
    int cur_x = x;
    int advance = 8 * scale;
    for (char c : text) {
        if (c == '\n') {
            y += 9 * scale;
            cur_x = x;
            continue;
        }
        draw_glyph(renderer, c, cur_x, y, color, scale);
        cur_x += advance;
    }
}

void RetroFont::draw_marquee_text(SDL_Renderer* renderer, const std::string& text, int x, int y, int max_w, int scroll_offset, Color color) {
    if (text.empty() || max_w <= 0) return;

    SDL_Rect clip = { x, y, max_w, 10 };
    SDL_RenderSetClipRect(renderer, &clip);

    int text_pixel_w = static_cast<int>(text.size()) * 8;
    int cur_x = x;

    if (text_pixel_w > max_w) {
        // Wrap around scroll
        int total_cycle = text_pixel_w + 40;
        int shift = scroll_offset % total_cycle;
        cur_x = x - shift;

        draw_text(renderer, text, cur_x, y + 1, color, 1);
        draw_text(renderer, text, cur_x + total_cycle, y + 1, color, 1);
    } else {
        draw_text(renderer, text, cur_x, y + 1, color, 1);
    }

    SDL_RenderSetClipRect(renderer, nullptr);
}

void RetroFont::draw_7seg_digit(SDL_Renderer* renderer, int digit, int x, int y, int w, int h, Color color) {
    if (digit < 0 || digit > 9) return;
    uint8_t segs = SEVEN_SEG_DIGITS[digit];

    int thick = std::max(1, w / 4);
    int mid_y = y + h / 2;

    SDL_SetRenderDrawColor(renderer, color.r, color.g, color.b, color.a);

    // Segments:
    // A: Top horizontal
    if (segs & (1 << 0)) {
        SDL_Rect r = { x + 1, y, w - 2, thick };
        SDL_RenderFillRect(renderer, &r);
    }
    // B: Top-right vertical
    if (segs & (1 << 1)) {
        SDL_Rect r = { x + w - thick, y + 1, thick, (h / 2) - 1 };
        SDL_RenderFillRect(renderer, &r);
    }
    // C: Bottom-right vertical
    if (segs & (1 << 2)) {
        SDL_Rect r = { x + w - thick, mid_y, thick, (h / 2) - 1 };
        SDL_RenderFillRect(renderer, &r);
    }
    // D: Bottom horizontal
    if (segs & (1 << 3)) {
        SDL_Rect r = { x + 1, y + h - thick, w - 2, thick };
        SDL_RenderFillRect(renderer, &r);
    }
    // E: Bottom-left vertical
    if (segs & (1 << 4)) {
        SDL_Rect r = { x, mid_y, thick, (h / 2) - 1 };
        SDL_RenderFillRect(renderer, &r);
    }
    // F: Top-left vertical
    if (segs & (1 << 5)) {
        SDL_Rect r = { x, y + 1, thick, (h / 2) - 1 };
        SDL_RenderFillRect(renderer, &r);
    }
    // G: Middle horizontal
    if (segs & (1 << 6)) {
        SDL_Rect r = { x + 1, mid_y - thick / 2, w - 2, thick };
        SDL_RenderFillRect(renderer, &r);
    }
}

void RetroFont::draw_led_clock(SDL_Renderer* renderer, int minutes, int seconds, bool is_negative, int x, int y, Color color) {
    if (minutes > 99) minutes = 99;
    if (seconds > 59) seconds = 59;
    if (seconds < 0) seconds = 0;

    int dig_w = 9;
    int dig_h = 16;
    int spacing = 11;

    int cur_x = x;

    // Minus sign if negative time
    if (is_negative) {
        SDL_SetRenderDrawColor(renderer, color.r, color.g, color.b, color.a);
        SDL_Rect minus = { cur_x, y + dig_h / 2 - 1, 6, 2 };
        SDL_RenderFillRect(renderer, &minus);
    }
    cur_x += 8;

    // Minutes (2 digits)
    draw_7seg_digit(renderer, minutes / 10, cur_x, y, dig_w, dig_h, color);
    cur_x += spacing;
    draw_7seg_digit(renderer, minutes % 10, cur_x, y, dig_w, dig_h, color);
    cur_x += spacing;

    // Colon
    SDL_SetRenderDrawColor(renderer, color.r, color.g, color.b, color.a);
    SDL_Rect dot1 = { cur_x + 1, y + 4, 2, 2 };
    SDL_Rect dot2 = { cur_x + 1, y + 10, 2, 2 };
    SDL_RenderFillRect(renderer, &dot1);
    SDL_RenderFillRect(renderer, &dot2);
    cur_x += 6;

    // Seconds (2 digits)
    draw_7seg_digit(renderer, seconds / 10, cur_x, y, dig_w, dig_h, color);
    cur_x += spacing;
    draw_7seg_digit(renderer, seconds % 10, cur_x, y, dig_w, dig_h, color);
}

void RetroFont::draw_led_track_num(SDL_Renderer* renderer, int track_num, int x, int y, Color color) {
    if (track_num < 0) track_num = 0;
    if (track_num > 99) track_num = track_num % 100;

    int dig_w = 6;
    int dig_h = 11;
    int spacing = 7;

    draw_7seg_digit(renderer, track_num / 10, x, y, dig_w, dig_h, color);
    draw_7seg_digit(renderer, track_num % 10, x + spacing, y, dig_w, dig_h, color);
}

